-- Runs inside the plugin project. Paths are relative to this file.
-- Luau is prebuilt in external/luau (see download_luau.bat)
defines { "LUMIX_STATIC_LUAU", "BUILDING_LUA" }
files { "src/**.h", "src/**.cpp" }
includedirs { "external/luau/include", "../../src", "src" }
filter "system:windows"
	libdirs { "external/luau/lib/win" }
	links { "Luau" }
	-- Luau.dll next to the executables; the static plugins are linked into engine_merged, which is in bin too
	postbuildcommands { '{COPYFILE} "' .. path.getabsolute("external/luau/lib/win/Luau.dll") .. '" "%{cfg.targetdir}"' }
filter "system:linux"
	libdirs { "external/luau/lib/linux" }
	links { "Luau" }
filter {}
if _OPTIONS["dynamic-plugins"] then
	links { "core", "engine" }
else
	-- the plugin is a part of a static library, the executables have to link Luau
	local exes = {}
	if not _OPTIONS["no-studio"] then table.insert(exes, "studio") end
	if not _OPTIONS["no-app"] then table.insert(exes, "app") end
	if _OPTIONS["with-tests"] then table.insert(exes, "tests") end

	local luau_abs = path.join(_SCRIPT_DIR, "external/luau/lib/win")
	for _, exe in ipairs(exes) do
		project(exe)
		filter "system:windows"
			libdirs { luau_abs }
			links { "Luau" }
			postbuildcommands { '{COPYFILE} "' .. luau_abs .. '/Luau.dll" "%{cfg.targetdir}"' }
		filter {}
	end

	-- the main script continues in the plugin's project
	project "engine_merged"
end


-- reflection for the Lua bindings is generated by the meta tool
project "meta"
	files { "src/meta_lua.cpp" }
